"""Baseline: which Figma frame and spec a generated screen came from.

`generate` writes <OutFile>.codegen.json next to the code (e.g. LoginScreen.kt.codegen.json).
Later commands (`status`, and the planned `diff` / `update`) read it to find the frame again,
compare the current design with the one the code was generated from, and tell whether a
developer has edited the file since.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import __version__

SCHEMA = 1
SUFFIX = ".codegen.json"
HEADER_MARK = "// Generated by figma-codegen"


class BaselineError(ValueError):
    """A baseline file exists but can't be used (corrupt JSON, unknown schema, missing fields)."""


@dataclass
class FigmaRef:
    """Where the frame lives. All None when the run used --figma-json without a URL."""
    file_key: str | None = None
    node_id: str | None = None
    url: str | None = None
    last_modified: str | None = None


@dataclass
class Baseline:
    platform: str
    screen: str
    package: str | None
    spec: dict
    code_sha256: str
    figma: FigmaRef = field(default_factory=FigmaRef)
    manifest_sha256: str | None = None
    tokens_sha256: str | None = None
    tool_version: str = __version__
    generated_at: str = ""
    model: str | None = None
    schema: int = SCHEMA
    path: Path | None = None   # where it was loaded from; not written

    def to_json(self) -> dict:
        d = asdict(self)
        d.pop("path")
        # schema first, then the fields in the order a human wants to read them
        return {"schema": d.pop("schema"), "figma": d.pop("figma"), **d}


def baseline_path(code_path: str | Path) -> Path:
    p = Path(code_path)
    return p.with_name(p.name + SUFFIX)


def code_path_for(baseline_file: str | Path) -> Path:
    """LoginScreen.kt.codegen.json -> LoginScreen.kt"""
    p = Path(baseline_file)
    if not p.name.endswith(SUFFIX):
        raise ValueError(f"not a baseline file: {p}")
    return p.with_name(p.name[: -len(SUFFIX)])


def sha256_file(path: str | Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _sha256_optional(path: str | Path | None) -> str | None:
    return sha256_file(path) if path and Path(path).is_file() else None


def header_lines(figma: FigmaRef, code_path: str | Path) -> list[str]:
    source = (f"from Figma {figma.file_key} node {figma.node_id}" if figma.file_key and figma.node_id
              else "from a saved Figma JSON (no frame URL)")
    return [f"{HEADER_MARK} {source}",
            f"// Baseline: {baseline_path(code_path).name} — visual layer; update with `figma-codegen update`"]


def add_header(code: str, figma: FigmaRef, code_path: str | Path) -> str:
    """Put the provenance comment on the first lines (before `package`), replacing an earlier one.

    Plain `//` comments: valid in Kotlin and Swift, and skipped by the design-system lint.
    """
    return "\n".join(header_lines(figma, code_path) + strip_header(code).splitlines()) + "\n"


def strip_header(code: str) -> str:
    """The code without the provenance comment `add_header` puts on the first lines."""
    lines = code.splitlines(keepends=True)
    if lines and lines[0].startswith(HEADER_MARK):
        lines = lines[2:] if len(lines) > 1 and lines[1].startswith("// Baseline:") else lines[1:]
    return "".join(lines)


def write_baseline(out_path: str | Path, spec: dict, figma_ref: FigmaRef, platform: str, screen: str,
                   package: str | None, cfg: Any, model: str | None) -> Path:
    """Write <out_path>.codegen.json for the code file that was just written at `out_path`.

    `cfg` provides manifest_path / tokens_path (hashed so a later run can tell the design system
    changed). The code hash is taken from the file on disk, so call this after writing the code.
    """
    b = Baseline(
        platform=platform, screen=screen, package=package, spec=spec,
        code_sha256=sha256_file(out_path), figma=figma_ref,
        manifest_sha256=_sha256_optional(getattr(cfg, "manifest_path", None)),
        tokens_sha256=_sha256_optional(getattr(cfg, "tokens_path", None)),
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
        model=model,
    )
    target = baseline_path(out_path)
    target.write_text(json.dumps(b.to_json(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return target


_REQUIRED = ("platform", "screen", "spec", "code_sha256")


def read_baseline_file(path: str | Path) -> Baseline:
    """Parse one baseline file; raises BaselineError with a message a human can act on."""
    p = Path(path)
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as e:
        raise BaselineError(f"{p}: not a readable baseline ({e}); delete it and run `generate` again") from e
    if not isinstance(data, dict):
        raise BaselineError(f"{p}: not a baseline (expected a JSON object)")
    schema = data.get("schema")
    if schema != SCHEMA:
        raise BaselineError(f"{p}: unknown baseline schema {schema!r} (this figma-codegen reads schema {SCHEMA}); "
                            "upgrade figma-codegen or regenerate the screen")
    missing = [k for k in _REQUIRED if not data.get(k)]
    if missing:
        raise BaselineError(f"{p}: baseline is missing {', '.join(missing)}; regenerate the screen")
    if not isinstance(data["spec"], dict):
        raise BaselineError(f"{p}: baseline spec is not an object; regenerate the screen")
    figma = data.get("figma") or {}
    if not isinstance(figma, dict):
        raise BaselineError(f"{p}: baseline 'figma' is not an object; regenerate the screen")
    return Baseline(
        platform=data["platform"], screen=data["screen"], package=data.get("package"), spec=data["spec"],
        code_sha256=data["code_sha256"],
        figma=FigmaRef(**{k: figma.get(k) for k in ("file_key", "node_id", "url", "last_modified")}),
        manifest_sha256=data.get("manifest_sha256"), tokens_sha256=data.get("tokens_sha256"),
        tool_version=data.get("tool_version") or "", generated_at=data.get("generated_at") or "",
        model=data.get("model"), schema=schema, path=p,
    )


def load_baseline(code_path: str | Path) -> Baseline | None:
    """The baseline of a code file; None when there is none. Raises BaselineError if it is unusable."""
    p = baseline_path(code_path)
    return read_baseline_file(p) if p.exists() else None


def is_code_modified(code_path: str | Path, baseline: Baseline) -> bool:
    """True when the code file differs from what `generate` wrote (or has been deleted)."""
    p = Path(code_path)
    return not p.is_file() or sha256_file(p) != baseline.code_sha256

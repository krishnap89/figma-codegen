"""Baseline files (<OutFile>.codegen.json), the provenance header and `figma-codegen status`."""
import json
from pathlib import Path

import openai
import pytest

from codegen.baseline import (SCHEMA, BaselineError, FigmaRef, add_header, baseline_path, is_code_modified,
                              load_baseline, sha256_file, write_baseline)
from codegen.config import Config
from codegen.validate import lint

from test_pipeline import FIXTURE, ROOT, URL, FakeClient, _run_cli

REF = FigmaRef("AbC123", "12:300", URL, "2026-10-01T09:00:00Z")
SPEC = {"screen": "LoginScreen", "root": {"type": "Column", "children": [{"type": "Text", "text": "Hi"}]}}
CFG = Config(manifest_path=str(ROOT / "manifest/components.json"), tokens_path=str(ROOT / "manifest/tokens.json"))

COMPOSE = """package com.x.login

@Composable
fun LoginScreen() { Column(Modifier.padding(AppTheme.spacing.m)) {} }
"""
SWIFTUI = """import SwiftUI

struct LoginScreen: View {
    var body: some View { VStack(spacing: Theme.spacing.m) { } }
}
"""


def _write(tmp_path, name="LoginScreen.kt", code=COMPOSE, ref=REF):
    out = tmp_path / name
    out.write_text(add_header(code, ref, out))
    write_baseline(out, SPEC, ref, "compose", "LoginScreen", "com.x.login", CFG, "qwen-coder")
    return out


def test_round_trip(tmp_path):
    out = _write(tmp_path)
    assert baseline_path(out).name == "LoginScreen.kt.codegen.json"
    raw = json.loads(baseline_path(out).read_text())
    assert raw["schema"] == SCHEMA and list(raw)[0] == "schema"
    assert raw["figma"] == {"file_key": "AbC123", "node_id": "12:300", "url": URL,
                            "last_modified": "2026-10-01T09:00:00Z"}
    assert raw["generated_at"].endswith("Z") and "path" not in raw
    b = load_baseline(out)
    assert b.spec == SPEC and b.platform == "compose" and b.screen == "LoginScreen"
    assert b.package == "com.x.login" and b.model == "qwen-coder" and b.figma == REF
    assert b.manifest_sha256 == sha256_file(CFG.manifest_path)
    assert b.tokens_sha256 == sha256_file(CFG.tokens_path)
    # the hash covers the file as written, header included
    assert b.code_sha256 == sha256_file(out)


def test_no_baseline_file(tmp_path):
    (tmp_path / "Hand.kt").write_text("fun x() {}\n")
    assert load_baseline(tmp_path / "Hand.kt") is None


def test_hash_changes_when_edited(tmp_path):
    out = _write(tmp_path)
    b = load_baseline(out)
    assert not is_code_modified(out, b)
    out.write_text(out.read_text() + "// my change\n")
    assert is_code_modified(out, b)
    out.unlink()
    assert is_code_modified(out, b)


@pytest.mark.parametrize("platform, code, name", [("compose", COMPOSE, "LoginScreen.kt"),
                                                  ("swiftui", SWIFTUI, "LoginScreen.swift")])
def test_header_first_and_lint_clean(tmp_path, platform, code, name):
    out = tmp_path / name
    text = add_header(code, REF, out)
    lines = text.splitlines()
    assert lines[0] == "// Generated by figma-codegen from Figma AbC123 node 12:300"
    assert lines[1] == f"// Baseline: {name}.codegen.json — visual layer; update with `figma-codegen update`"
    assert lines[2] == code.splitlines()[0]   # `package` / `import` follows directly
    assert lint(text, platform) == [] and lint(code, platform) == []


def test_header_without_url_and_not_duplicated(tmp_path):
    out = tmp_path / "LoginScreen.kt"
    once = add_header(COMPOSE, FigmaRef(), out)
    assert once.startswith("// Generated by figma-codegen from a saved Figma JSON (no frame URL)\n")
    twice = add_header(once, REF, out)
    assert twice.count("// Generated by figma-codegen") == 1 and "node 12:300" in twice


@pytest.mark.parametrize("content, msg", [
    ("{not json", "not a readable baseline"),
    ("[]", "expected a JSON object"),
    (json.dumps({"schema": 99}), "unknown baseline schema 99"),
    (json.dumps({"schema": SCHEMA, "platform": "compose"}), "missing screen, spec, code_sha256"),
])
def test_corrupt_baseline_clear_error(tmp_path, content, msg):
    code = tmp_path / "X.kt"
    code.write_text("x\n")
    baseline_path(code).write_text(content)
    with pytest.raises(BaselineError, match=msg):
        load_baseline(code)


# --- CLI ---------------------------------------------------------------------------------------

GOOD = "```kotlin\npackage com.x.login\n\nfun LoginScreen() { Column(Modifier.padding(AppTheme.spacing.m)) {} }\n```"
BAD = "```kotlin\nfun LoginScreen() { Column(Modifier.padding(16.dp)) {} }\n```"


def _generate(monkeypatch, tmp_path, turns, *extra):
    client = FakeClient(turns)
    monkeypatch.setattr(openai, "OpenAI", lambda **kw: client)
    monkeypatch.setenv("CODEGEN_USE_TOOLS", "false")
    return _run_cli(monkeypatch, tmp_path, ["generate", *extra, "--platform", "compose",
                                            "--out", "out/LoginScreen.kt", "--package", "com.x.login"])


def test_generate_writes_baseline_and_header(monkeypatch, tmp_path, capsys):
    assert _generate(monkeypatch, tmp_path, [(GOOD, None)], URL) == 0
    out = tmp_path / "out/LoginScreen.kt"
    assert out.read_text().splitlines()[:3] == [
        "// Generated by figma-codegen from Figma AbC123 node 12:300",
        "// Baseline: LoginScreen.kt.codegen.json — visual layer; update with `figma-codegen update`",
        "package com.x.login"]
    b = load_baseline(out)
    assert b.figma.url == URL and b.figma.node_id == "12:300" and b.screen == "LoginScreen"
    assert b.spec["screen"] == "LoginScreen" and b.package == "com.x.login"
    assert not is_code_modified(out, b)
    assert "baseline: out/LoginScreen.kt.codegen.json" in capsys.readouterr().out


def test_generate_offline_without_url_has_null_figma(monkeypatch, tmp_path):
    assert _generate(monkeypatch, tmp_path, [(GOOD, None)], "--figma-json", str(FIXTURE)) == 0
    b = load_baseline(tmp_path / "out/LoginScreen.kt")
    assert b.figma == FigmaRef(None, None, None, None)


def test_generate_failure_writes_no_baseline(monkeypatch, tmp_path):
    monkeypatch.setenv("CODEGEN_MAX_ROUNDS", "1")
    assert _generate(monkeypatch, tmp_path, [(BAD, None)], URL) == 1
    assert (tmp_path / "out/LoginScreen.kt.draft").exists()
    assert not list((tmp_path / "out").glob("*.codegen.json"))


def test_generate_no_baseline_flag(monkeypatch, tmp_path):
    assert _generate(monkeypatch, tmp_path, [(GOOD, None)], URL, "--no-baseline") == 0
    out = tmp_path / "out/LoginScreen.kt"
    assert out.read_text().startswith("package com.x.login")
    assert not baseline_path(out).exists()


def test_status_modified_and_unmodified(monkeypatch, tmp_path, capsys):
    src = tmp_path / "src"
    src.mkdir()
    clean = _write(src, "LoginScreen.kt")
    edited = _write(src, "SignupScreen.kt", ref=FigmaRef())
    edited.write_text(edited.read_text() + "// tweak\n")
    assert _run_cli(monkeypatch, tmp_path, ["status", "src"]) == 0
    out = capsys.readouterr().out
    assert f"{Path('src') / 'LoginScreen.kt'}  unmodified" in out
    assert f"{Path('src') / 'SignupScreen.kt'}  modified since generation" in out
    assert "Figma AbC123 node 12:300 · generated" in out and "Figma: saved JSON, no frame URL" in out
    # one file
    assert _run_cli(monkeypatch, tmp_path, ["status", str(clean)]) == 0
    assert "unmodified" in capsys.readouterr().out



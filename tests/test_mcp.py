# --- the real protocol, where the SDK is installed ------------------------------------------------

def test_protocol_round_trip(tools):
    pytest.importorskip("mcp")
    import anyio
    from mcp.shared.memory import create_connected_server_and_client_session
    from codegen.mcp_server import build_server

    server = build_server(tools)

    async def run():
        async with create_connected_server_and_client_session(server._mcp_server) as client:
            listed = await client.list_tools()
            assert {t.name for t in listed.tools} == set(TOOLS)
            schema = next(t for t in listed.tools if t.name == "generate_screen").inputSchema
            assert schema["required"] == ["figma_url", "platform"]
            res = await client.call_tool("get_figma_spec", {"figma_url": URL})
            data = json.loads(res.content[0].text)
            assert data["command"] == "spec" and data["spec"]["screen"] == "LoginScreen"
            res = await client.call_tool("diff_design", {"code_path": "/etc/passwd"})
            assert json.loads(res.content[0].text)["error"]["type"] == "workspace"
            prompts = await client.list_prompts()
            assert {p.name for p in prompts.prompts} == {"implement-figma-screen", "update-screen-from-design"}
            templates = await client.list_resource_templates()
            assert {t.uriTemplate for t in templates.resourceTemplates} == {
                "figma-codegen://manifest/{platform}", "figma-codegen://tokens/{platform}"}
            res = await client.read_resource("figma-codegen://tokens/compose")
            assert "spacing.m -> AppTheme.spacing.m" in res.contents[0].text

    anyio.run(run)

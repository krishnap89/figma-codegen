def test_paths_outside_the_workspace_are_rejected(tools, env, tmp_path_factory):
    outside = tmp_path_factory.mktemp("elsewhere") / "X.kt"
    outside.write_text("x")
    for call in (dict(tool="diff_design", code_path=str(outside)),
                 dict(tool="diff_design", code_path="../" + outside.parent.name + "/X.kt"),
                 dict(tool="update_screen", code_path=str(outside), apply=True),
                 dict(tool="generate_screen", figma_url=URL, platform="compose", out_path="../../evil.kt")):
        res = tools.call(**call)
        assert res["status"] == "error" and res["error"]["type"] == "workspace", call
    assert outside.read_text() == "x"



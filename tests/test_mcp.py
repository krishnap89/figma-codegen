def cli_json(capsys, *argv):
    cli.main(["--json", *argv])
    return json.loads(capsys.readouterr().out)


def same(a, b):
    drop = {"duration_s"}
    return {k: v for k, v in a.items() if k not in drop} == {k: v for k, v in b.items() if k not in drop}



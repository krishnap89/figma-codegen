def test_design_system_tools(tools):
    comps = tools.call("list_components", platform="compose")
    assert COMMON <= set(comps) and comps["status"] == "success"
    button = next(c for c in comps["components"] if c["name"] == "Button")
    assert button["description"].startswith("Primary action button") and button["code"].endswith("UiButton")

    doc = tools.call("get_component_docs", name="Button", platform="compose")
    assert "UiButton(" in doc["component"]["compose"]["signature"] and "swiftui" not in doc["component"]

    toks = tools.call("list_tokens", category="spacing", platform="compose")
    assert {"token": "spacing.m", "code": "AppTheme.spacing.m", "value": "16px"} in toks["tokens"]

    bad = tools.call("get_component_docs", name="Nope", platform="compose")
    assert bad["status"] == "error" and "available: Button" in bad["error"]["message"]
    assert tools.call("list_tokens", category="nope", platform="compose")["error"]["type"] == "usage"
    assert tools.call("list_components", platform="android")["error"]["type"] == "usage"


def test_lint_and_compile_check(tools):
    ok = tools.call("lint_design_system", code="val x = AppTheme.spacing.m", platform="compose")
    assert ok["status"] == "success" and ok["issues"] == []
    bad = tools.call("lint_design_system", code="val x = 16.dp", platform="compose")

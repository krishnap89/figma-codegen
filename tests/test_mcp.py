def test_every_call_is_traced(tools, env):
    tools.call("lint_design_system", code="x" * 5000, platform="compose")
    tools.call("diff_design", code_path="/etc/passwd")
    lines = [json.loads(line) for f in (env / "traces").glob("mcp-*.jsonl") for line in f.open()]
    assert [e["tool"] for e in lines] == ["lint_design_system", "diff_design"]
    assert lines[0]["args"] == {"code": "<5000 chars>", "platform": "compose"} and lines[0]["status"] == "success"
    assert lines[1]["status"] == "error" and "outside the workspace" in lines[1]["error"]
    assert all(e["duration_s"] >= 0 for e in lines)


